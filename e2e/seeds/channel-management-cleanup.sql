WHERE channel_id IN ('01JTE2E143B000000000000R01', '01JTE2E143B000000000000R02', '01JTE2E143B000000000000R03', '01JTE2E143B000000000000R04',
                     '01JTE2E143B000000000000C01', '01JTE2E143B000000000000C02', '01JTE2E143B000000000000C03')
   OR archived_by IN (SELECT id FROM users WHERE login_id LIKE 'e2euser!_chmgmt!_%' ESCAPE '!')
   OR restored_by IN (SELECT id FROM users WHERE login_id LIKE 'e2euser!_chmgmt!_%' ESCAPE '!');
DELETE FROM thread_read_positions
WHERE user_id IN (SELECT id FROM users WHERE login_id LIKE 'e2euser!_chmgmt!_%' ESCAPE '!')
   OR parent_message_id IN (SELECT id FROM messages WHERE room_id IN (
        '01JTE2E143B000000000000R01', '01JTE2E143B000000000000R02', '01JTE2E143B000000000000R03', '01JTE2E143B000000000000R04',
        '01JTE2E143B000000000000C01', '01JTE2E143B000000000000C02', '01JTE2E143B000000000000C03'));
