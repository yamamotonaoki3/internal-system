                  '01JTE2E143B000000000000C01', '01JTE2E143B000000000000C02', '01JTE2E143B000000000000C03')
  AND parent_message_id IS NOT NULL;
DELETE FROM messages
WHERE room_id IN ('01JTE2E143B000000000000R01', '01JTE2E143B000000000000R02', '01JTE2E143B000000000000R03', '01JTE2E143B000000000000R04',
                  '01JTE2E143B000000000000C01', '01JTE2E143B000000000000C02', '01JTE2E143B000000000000C03');
