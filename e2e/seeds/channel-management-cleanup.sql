-- シードの固定のルーム（01JTE2E143B000000000000R01〜R04・C01〜C03）の識別子だけを後始末する。ほかのシードには触れない。
-- 外部キーの順：アーカイブの記録（チャンネル・社員を指す）→ スレッドの既読・既読位置 → メンション・リアクション・添付 → メッセージ（返信 → 親）→ 通知
--   → 参加者 → チャンネル（deleted_by が社員を指す）→ ルーム → 監査 → セッション → ロール → 社員 → 部署。
-- 管理の監査（channel.archive・channel.restore）・再認証の監査と、通知（channel.archived・channel.restored）は、操作者・宛先が e2euser_chmgmt_ の行と、
-- 対象がシードのルームの行として消す（既存の E2E の後始末と同じ扱い）。
